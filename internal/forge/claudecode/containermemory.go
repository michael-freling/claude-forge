package claudecode

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/michael-freling/claude-forge/internal/forge/layout"
)

const (
	// ContainerMemoryFile is the name of the forge-managed CLAUDE.md inside the
	// config directory (~/.config/claude-forge/).
	ContainerMemoryFile = "container-CLAUDE.md"

	// ContainerMemoryTarget is where that file is mounted in the agent container:
	// Claude Code's managed-memory path, which is loaded on every run. See
	// layout.ManagedMemory for why it is not /CLAUDE.md.
	ContainerMemoryTarget = layout.ManagedMemory

	// workspacePlaceholder is replaced with layout.Workspace when the file is
	// rendered, so the instructions cannot drift from the real mount point.
	workspacePlaceholder = "{{workspace}}"
)

// containerMemoryTemplate tells the agent what it cannot observe about its own
// environment: that it runs in a throwaway container rather than on the user's
// machine, that the workspace is a bind mount whose absolute path means nothing
// to the user on the other side, and that GitHub is reachable only through the
// session's gateway (which is what makes private repositories work here).
const containerMemoryTemplate = `# Container environment (claude-forge)

<!-- Generated by claude-forge. Regenerated at the start of every session;
     edits here are overwritten. Put your own instructions in the project's
     CLAUDE.md, or in ~/.claude/rules/ on the host (mounted into every
     session). -->

## You are running inside a container, not on the host

This session runs inside a claude-forge container, not on the user's machine.
The filesystem, installed packages, processes, environment variables, and
network are the container's own, and everything outside the mounted paths is
discarded when the session ends.

So: never describe container state as if it were the host's, and never assume a
tool, service, port, or file the user has on their machine is reachable here —
check before relying on it. Installing packages or writing files outside the
mounted paths affects only this container, so do not offer such changes as
lasting fixes to the user's setup.

## Refer to files by their path relative to ` + "`" + workspacePlaceholder + "`" + `

The user's project directory on the host is bind-mounted at ` + "`" + workspacePlaceholder + "`" + `,
which is also the working directory. The same files sit under a different
absolute path on the host, so a container-absolute path is not a path the user
can use.

When you name a file or directory to the user — in replies, summaries, commit
messages, PR descriptions — write it relative to ` + "`" + workspacePlaceholder + "`" + `:

- Yes: ` + "`internal/forge/orchestrator.go`" + `
- No: ` + "`" + workspacePlaceholder + "/internal/forge/orchestrator.go`" + `

This is about what you show the user. Tool calls still take real container paths,
so keep using ` + "`" + workspacePlaceholder + "/...`" + ` where a tool requires an absolute
path. Paths outside the workspace (` + "`/home/user/...`, `/etc/...`" + `) exist only in
this container; mention them only when the container is the subject.

## Reach GitHub through the gateway

This container holds no GitHub credentials and has no ` + "`gh`" + ` CLI. Git traffic to
GitHub goes through the session's gateway, which attaches the user's token on the
way out — so private repositories work here without any setup, as long as the
request goes through the gateway.

` + "`~/.gitconfig`" + ` rewrites ` + "`https://github.com/`" + ` to the gateway, so the ordinary
form already works, for this project and for any other repository:

    git clone https://github.com/<owner>/<repo>.git

SSH remotes are not proxied. When a remote is ` + "`git@github.com:...`" + ` — often the
case for ` + "`origin`" + ` — ` + "`git fetch origin`" + ` fails outright (no keys, and
` + "`GIT_TERMINAL_PROMPT=0`" + ` makes it fail instead of prompting). Go through the
gateway explicitly rather than rewriting the user's remotes:

    git fetch http://gateway:8080/github.com/<owner>/<repo>.git <branch>

What the gateway permits:

- Clone and fetch: any repository.
- Push: only this session's own repository,
  ` + "`$FORGE_PROJECT_OWNER/$FORGE_PROJECT_REPO`" + `. Pushing anywhere else returns 403.
- Nothing else: the GitHub REST API is not proxied, and direct calls to
  api.github.com from here are unauthenticated. Use the ` + "`github`" + ` MCP tools for
  pull requests, issues, reviews and other API work.
`

// DefaultContainerMemory returns the content of the forge-managed container
// CLAUDE.md, with the workspace path filled in from layout.Workspace.
func DefaultContainerMemory() string {
	return strings.ReplaceAll(containerMemoryTemplate, workspacePlaceholder, layout.Workspace)
}

// WriteContainerMemory writes the container CLAUDE.md into configDir and
// returns its path. The directory is created if needed.
//
// The file is regenerated on every session (like gitconfig, unlike
// settings.json) so that instruction changes ship with claude-forge instead of
// being pinned by whatever a first run wrote. User- and project-level
// instructions therefore do not belong here: they belong in the project's
// CLAUDE.md, or in the host's ~/.claude/rules/ (mounted into the agent and read
// as user memory; note the host's ~/.claude/CLAUDE.md is not mounted).
func WriteContainerMemory(configDir string) (string, error) {
	if err := os.MkdirAll(configDir, 0o755); err != nil {
		return "", fmt.Errorf("failed to create config directory: %w", err)
	}

	path := filepath.Join(configDir, ContainerMemoryFile)
	if err := os.WriteFile(path, []byte(DefaultContainerMemory()), 0o644); err != nil {
		return "", fmt.Errorf("failed to write %s: %w", ContainerMemoryFile, err)
	}
	return path, nil
}
